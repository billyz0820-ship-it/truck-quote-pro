-- Create table for ZIP prefix to region mapping
CREATE TABLE public.zip_region_mapping (
  id UUID NOT NULL DEFAULT gen_random_uuid() PRIMARY KEY,
  zip_prefix TEXT NOT NULL,
  region TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  UNIQUE(zip_prefix)
);

-- Enable RLS
ALTER TABLE public.zip_region_mapping ENABLE ROW LEVEL SECURITY;

-- Create policies
CREATE POLICY "所有用户可以查看邮编地区映射" 
ON public.zip_region_mapping 
FOR SELECT 
USING (true);

CREATE POLICY "管理员可以管理邮编地区映射" 
ON public.zip_region_mapping 
FOR ALL 
USING (has_role(auth.uid(), 'admin'::app_role))
WITH CHECK (has_role(auth.uid(), 'admin'::app_role));

-- Create trigger for updated_at
CREATE TRIGGER update_zip_region_mapping_updated_at
BEFORE UPDATE ON public.zip_region_mapping
FOR EACH ROW
EXECUTE FUNCTION public.update_updated_at_column();

